def ts(sec):
    return time.strftime("%Y-%m-%dT%H:%M:%S", time.gmtime(1763460000 + sec)) + ".250Z"


def at(sec):
    return (1763460000 + sec) * 1000 + 250


def user(sec, content, **kw):
    d = {"type": "user", "timestamp": ts(sec), "isSidechain": False, "message": {"role": "user", "content": content}}
    d.update(kw)
    return d


def assistant(sec, mid, *blocks, **kw):
    d = {"type": "assistant", "timestamp": ts(sec), "isSidechain": False,
         "message": {"id": mid, "role": "assistant", "model": "claude-x", "content": list(blocks)}}
    d.update(kw)
    return d


def text(t):
    return {"type": "text", "text": t}


def tool(name, tid="t", **inp):
    return {"type": "tool_use", "id": tid, "name": name, "input": inp}


def result(sec, tid, extra=None):
    d = user(sec, [{"type": "tool_result", "tool_use_id": tid, "content": "SECRET OUTPUT"}])
    d["toolUseResult"] = extra if extra is not None else {"stdout": "SECRET OUTPUT"}
    return d


